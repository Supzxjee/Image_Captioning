def esc(s): return html.escape(str(s))

class Figure:
    def __init__(self, slug, w, h, title):
        self.slug,self.w,self.h,self.title=slug,w,h,title
        self.bg=[];self.edges=[];self.nodes=[];self.meta=[];self.routes=[]
    def text(self,x,y,s,size=22,bold=False,anchor='middle',owner=None):
        own=f' data-owner="{owner}"' if owner else ''
        return f'<text x="{x}" y="{y}" font-size="{size}" font-weight="{600 if bold else 400}" text-anchor="{anchor}"{own}>{esc(s)}</text>'
    def note(self,x,y,s,size=20,bold=False,anchor='middle'):
        self.nodes.append(self.text(x,y,s,size,bold,anchor))
    def frame(self,id,x,y,w,h,title,dashed=True,fs=28):
        ds=' stroke-dasharray="10 7"' if dashed else ''
        self.bg.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="0" fill="#fff" stroke="#B4BFC6" stroke-width="1.4"{ds}/>'+self.text(x+24,y+40,title,fs,True,'start'))
    def badge(self,kind,x,y,owner):
        if kind=='frozen':
            paths=['M10 0 V20','M1.34 5 L18.66 15','M1.34 15 L18.66 5', 'M10 3 L7 5 M10 3 L13 5 M10 17 L7 15 M10 17 L13 15', 'M3.94 6.5 L4.7 10 M3.94 6.5 L7.5 6 M16.06 13.5 L12.5 14 M16.06 13.5 L15.3 10', 'M3.94 13.5 L7.5 14 M3.94 13.5 L4.7 10 M16.06 6.5 L15.3 10 M16.06 6.5 L12.5 6']
            glyph=''.join(f'<path d="{p}"/>' for p in paths);stroke='#1677B8';fill='none'
        else:
            glyph='<path d="M11 0 C15 7 7 8 13 12 C15 10 16 8 16 6 C22 14 19 23 10 23 C1 23 -1 15 4 9 C4 13 6 14 7 13 C3 7 11 6 11 0 Z"/><path d="M10 14 C15 18 14 21 10 21 C6 21 6 18 10 14 Z"/>'
            stroke='#D95F1A';fill='#F6A23A'
        self.nodes.append(f'<g data-icon-kind="{kind}" data-module="{owner}" transform="translate({x} {y}) scale(.8)" fill="{fill}" stroke="{stroke}" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">{glyph}</g>')
    def box(self,id,x,y,w,h,lines,fill=VIS,data=False,kind=None,fs=22):
        if isinstance(lines,str):lines=[lines]
        self.meta.append(dict(id=id,x=x,y=y,w=w,h=h,kind='data' if data else 'module'))
        self.nodes.append(f'<g id="{id}"><rect data-node-id="{id}" x="{x}" y="{y}" width="{w}" height="{h}" rx="{0 if data else 8}" fill="{fill}" stroke="{BORDER}" stroke-width="1.4"/>')
        step=fs+7; cy=y+h/2-(len(lines)-1)*step/2+fs*.34
        for j,s in enumerate(lines):self.nodes.append(self.text(x+w/2-(8 if kind else 0),cy+j*step,s,fs,j==0,'middle',id))
        self.nodes.append('</g>')
        if kind:self.badge(kind,x+w-23,y+7,id)
    def dot(self,id,x,y):
        self.nodes.append(f'<circle cx="{x}" cy="{y}" r="4" fill="{LINE}"/>')
        self.meta.append(dict(id=id,x=x-4,y=y-4,w=8,h=8,kind='junction'))
    def plus(self,id,x,y):
        self.nodes.append(f'<g><circle data-node-id="{id}" cx="{x}" cy="{y}" r="20" fill="#fff" stroke="{LINE}" stroke-width="1.7"/>'+self.text(x,y+9,'+',28,owner=id)+'</g>')
        self.meta.append(dict(id=id,x=x-20,y=y-20,w=40,h=40,kind='sum'))
    def edge(self,id,pts,src=None,dst=None,dash=False,arrow=True):
        assert all(a[0]==b[0] or a[1]==b[1] for a,b in zip(pts,pts[1:])),id
        assert all(a!=b for a,b in zip(pts,pts[1:])),id
        d='M '+' L '.join(f'{x},{y}' for x,y in pts)
        ds=' stroke-dasharray="7 5"' if dash else ''
        ma=' marker-end="url(#arrow)"' if arrow else ''
        self.edges.append(f'<path data-edge="{id}" d="{d}" fill="none" stroke="{LINE}" stroke-width="1.7"{ds}{ma}/>')
        self.routes.append(dict(id=id,points=pts,src=src,dst=dst,guide=not arrow))
    def content(self):return ''.join(self.bg+self.edges+self.nodes)
    def place(self,other,x,y):
        self.nodes.append(f'<g transform="translate({x} {y})">{other.content()}</g>')
        self.meta.extend([dict(n,x=n['x']+x,y=n['y']+y) for n in other.meta])
        self.routes.extend([dict(r,points=[(px+x,py+y) for px,py in r['points']]) for r in other.routes])
    def save(self,caption=''):
        slug=self.slug
        svg=f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {self.w} {self.h}" role="img" aria-labelledby="{slug}-title {slug}-desc"><title id="{slug}-title">{esc(self.title)}</title><desc id="{slug}-desc">An image captioning architecture with explicit semantic, prompt, generation and selection mechanisms.</desc><defs><marker id="arrow" viewBox="0 0 10 8" refX="9" refY="4" markerWidth="7" markerHeight="6" orient="auto"><path d="M0,0 L10,4 L0,8 Z" fill="{LINE}"/></marker></defs><rect width="{self.w}" height="{self.h}" fill="#fff"/>'+self.content()+'</svg>'
        page=f'''<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>{esc(self.title)}</title><style>body{{margin:0;background:#fff;color:{INK};font-family:Arial,"Liberation Sans",sans-serif}}main{{max-width:100%;min-width:0}}.diagram-container{{width:100%;overflow-x:auto}}svg{{width:100%;min-width:{self.w}px;display:block;font-family:Arial,"Liberation Sans",sans-serif;color:{INK}}}text{{fill:{INK}}}figcaption{{max-width:1000px;margin:20px auto;padding:16px;font-size:16px;line-height:1.6}}@media print{{.diagram-container{{overflow:visible}}svg{{min-width:0}}figcaption{{display:none}}}}</style></head><body><main><div class="diagram-container">{svg}</div><figcaption>{esc(caption)}</figcaption></main></body></html>'''
        (ROOT/(slug+'.html')).write_text(page)
        return dict(slug=slug,w=self.w,h=self.h,title=self.title,nodes=self.meta,routes=self.routes)

